public class main {
    public static void main(String[] args){

        int intOperandA = 1;
        int intOperandB = 2;
        int intSum = intOperandA + intOperandB;

        double doubleOperandA = 5.00;
        double doubleOperandB = 2.50;
        double doubleDifference = doubleOperandA - doubleOperandB;

        System.out.println("The sum using ints of " + intOperandA + " " + intOperandB + " is " + intSum);
        System.out.println("The difference using ints of " + doubleOperandA + " " + doubleOperandB + " is " + doubleDifference);
    }
}
